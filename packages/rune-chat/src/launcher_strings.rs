pub fn get(locale: &str, key: &str) -> Option<&'static str> {
    let index = KEYS.iter().position(|k| *k == key)?;
    Some(
        CATALOG
            .iter()
            .find(|(id, _)| *id == locale)
            .unwrap_or(&CATALOG[0])
            .1[index],
    )
}
